// Generates supabase/migrations/20261118000200_catalogue_seed.sql from the
// EXISTING catalogue in lib/data/product_data.dart.
//
// No prices or products are typed by hand: every row is derived from the
// `ProductData.sampleProducts` records the website already ships. Re-run this
// whenever the catalogue changes, then apply the migration:
//
//   dart run tool/export_catalogue_sql.dart
//
// The server uses this table to recalculate order totals so the browser can
// never dictate prices.
import 'dart:io';

import 'package:sage_studio/data/product_data.dart';
import 'package:sage_studio/models/product_model.dart';

String _q(String s) => "'${s.replaceAll("'", "''")}'";
String _num(double v) => v.toStringAsFixed(2);

void main() {
  const products = ProductData.sampleProducts;
  final ids = <String>{};
  final b = StringBuffer()
    ..writeln('-- GENERATED by tool/export_catalogue_sql.dart from lib/data/product_data.dart.')
    ..writeln('-- Do not edit by hand. Products: ${products.length}.')
    ..writeln('-- Upserts keep the server price list in sync with the website catalogue;')
    ..writeln('-- products removed from the website are marked inactive (never deleted).')
    ..writeln()
    ..writeln('begin;')
    ..writeln()
    ..writeln('insert into public.catalogue_products')
    ..writeln(
        '  (product_id, code, title, subtitle, clan, image_path, price_ksh, cover_only_price_ksh, price_label, active)')
    ..writeln('values');

  final rows = <String>[];
  for (final Product p in products) {
    if (!ids.add(p.id)) {
      stderr.writeln('Duplicate product id in catalogue: ${p.id}');
      exitCode = 1;
      return;
    }
    rows.add('  (${_q(p.id)}, ${_q(p.code)}, ${_q(p.title)}, ${_q(p.subtitle)}, ${_q(p.clan)}, '
        '${_q(p.mainImage)}, ${_num(p.priceKsh)}, '
        '${p.coverOnlyPriceKsh == null ? 'null' : _num(p.coverOnlyPriceKsh!)}, '
        '${p.priceKshLabel == null ? 'null' : _q(p.priceKshLabel!)}, true)');
  }
  b
    ..writeln(rows.join(',\n'))
    ..writeln('on conflict (product_id) do update set')
    ..writeln('  code = excluded.code,')
    ..writeln('  title = excluded.title,')
    ..writeln('  subtitle = excluded.subtitle,')
    ..writeln('  clan = excluded.clan,')
    ..writeln('  image_path = excluded.image_path,')
    ..writeln('  price_ksh = excluded.price_ksh,')
    ..writeln('  cover_only_price_ksh = excluded.cover_only_price_ksh,')
    ..writeln('  price_label = excluded.price_label,')
    ..writeln('  active = true,')
    ..writeln('  updated_at = now();')
    ..writeln()
    ..writeln('update public.catalogue_products set active = false, updated_at = now()')
    ..writeln('where product_id not in (${ids.map(_q).join(', ')});')
    ..writeln()
    ..writeln('commit;');

  final out = File('supabase/migrations/20261118000200_catalogue_seed.sql');
  out.parent.createSync(recursive: true);
  out.writeAsStringSync(b.toString());
  final labelled = products.where((p) => p.priceKshLabel != null).map((p) => p.id).toList();
  stdout.writeln('Wrote ${products.length} products to ${out.path}');
  if (labelled.isNotEmpty) {
    stdout.writeln('Note: ${labelled.length} products have display price labels (sale/discount/range); '
        'the numeric priceKsh used by the existing cart is what the server will charge: ${labelled.join(', ')}');
  }
}
